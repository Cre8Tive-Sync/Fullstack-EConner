function mergePoiOverride(basePoi, override, fallbackIndex) {
  const categoryId = override.category_id || basePoi?.category_id || CATEGORIES[0].id
  const category = getCategoryForPlace(categoryId)
  const categoryIndex = Math.max(CATEGORIES.findIndex((item) => item.id === categoryId), 0)
  const fallbackCoords = buildPlaceholderCoords(categoryIndex, fallbackIndex)
  const operatingHours = override.operating_hours ?? basePoi?.operating_hours ?? []
  const overrideImages = Array.isArray(override.images) ? override.images.filter(Boolean) : []

  return {
    id: override.id ?? basePoi?.id ?? `${categoryId}-${override.slug || slugify(override.name)}`,
    google_place_id: override.google_place_id ?? basePoi?.google_place_id ?? null,
    name: override.name ?? basePoi?.name ?? '',
    description: override.description ?? basePoi?.description ?? '',
    address: override.address ?? basePoi?.address ?? '',
    municipality: override.municipality ?? basePoi?.municipality ?? 'Conner',
    province: override.province ?? basePoi?.province ?? 'Apayao',
    lat: override.lat ?? basePoi?.lat ?? fallbackCoords.lat,
    lng: override.lng ?? basePoi?.lng ?? fallbackCoords.lng,
    category_id: categoryId,
    rating: override.rating ?? basePoi?.rating ?? null,
    total_reviews: override.total_reviews ?? basePoi?.total_reviews ?? 0,
    phone: override.phone ?? basePoi?.phone ?? null,
    website: override.website ?? basePoi?.website ?? null,
    google_maps_url: override.google_maps_url ?? basePoi?.google_maps_url ?? null,
    slug: override.slug ?? basePoi?.slug ?? slugify(override.name),
    operating_hours: operatingHours,
    tags: override.tags ?? basePoi?.tags ?? [],
    images: overrideImages.length > 0 ? overrideImages : basePoi?.images ?? [],
    videoUrl: override.videoUrl ?? basePoi?.videoUrl ?? null,
    is_active: override.is_active ?? basePoi?.is_active ?? true,
    sphereColor: override.sphereColor ?? basePoi?.sphereColor ?? category.sphereColor,
    sphereEmissive: override.sphereEmissive ?? basePoi?.sphereEmissive ?? category.sphereEmissive,
    proximityRadius: override.proximityRadius ?? basePoi?.proximityRadius ?? category.proximityRadius,
    hours: override.hours ?? formatOperatingHours(operatingHours) ?? basePoi?.hours ?? 'Details coming soon',
    modelUrl: override.modelUrl ?? basePoi?.modelUrl ?? null,
  }
}

const BASE_POIS = buildBasePois()
const BASE_POI_INDEX = new Map(BASE_POIS.map((poi, index) => [poi.slug, index]))

export const POIS = (() => {
  const pois = BASE_POIS.map((poi) => ({ ...poi }))

  PLACE_DATA_OVERRIDES.forEach((override, index) => {
    const matchIndex = BASE_POI_INDEX.get(override.slug)

    if (matchIndex == null) {
      pois.push(mergePoiOverride(null, override, BASE_POIS.length + index))
      return
    }

    pois[matchIndex] = mergePoiOverride(pois[matchIndex], override, matchIndex)
  })

  return pois
})()
