export function getCategoryForPlace(categoryId) {
  return CATEGORIES.find((c) => c.id === categoryId) || CATEGORIES[0]
}

const DAY_NAMES = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']

export function formatOperatingHours(hours) {
  if (!hours || hours.length === 0) return ''

  const allNull = hours.every((d) => d.open_time == null && d.close_time == null)
  if (allNull) {
    const allOpen = hours.every((d) => !d.is_closed)
    return allOpen ? 'Open 24 hours' : 'Hours vary'
  }

  const groups = {}
  for (const d of hours) {
    if (d.is_closed) continue
    const key = `${d.open_time}-${d.close_time}`
    if (!groups[key]) groups[key] = []
    groups[key].push(DAY_NAMES[d.day_of_week])
  }

  const parts = Object.entries(groups).map(([key, days]) => {
    const [open, close] = key.split('-')
    const dayStr = days.length === 7 ? 'Daily' : days.join(', ')
    return `${dayStr} ${open}–${close}`
  })

  return parts.join('; ')
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function displayNameFromFolder(folderName) {
  return folderName
    .replace(/_s\b/g, "'s")
    .replace(/_/g, ' ')
}

function mediaPaths(folder, files) {
  return files.map((file) => encodeURI(`/img/media/${folder}/${file}`))
}

function buildPlaceholderCoords(categoryIndex, placeIndex) {
  const baseLat = 17.808
  const baseLng = 121.306

  return {
    lat: Number((baseLat + categoryIndex * 0.012 + placeIndex * 0.0011).toFixed(6)),
    lng: Number((baseLng + categoryIndex * 0.009 + placeIndex * 0.0013).toFixed(6)),
  }
}

